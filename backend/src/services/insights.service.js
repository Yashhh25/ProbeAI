const interviewInsightsRepository = require('../repositories/interview-insights.repository');
const interviewRepository = require('../repositories/interview.repository');
const messageRepository = require('../repositories/message.repository');
const InsightsPromptBuilder = require('../ai/prompts/insights.prompt');
const { getProvider } = require('../ai/providers/provider.factory');

class InsightsService {
  constructor() {
    this.promptBuilder = new InsightsPromptBuilder();
  }

  async generateInsights(interviewId) {
    const interview = await interviewRepository.findById(interviewId);
    if (!interview) {
      throw new Error('Interview not found');
    }

    const transcript = await messageRepository.getTranscript(interviewId);
    const lastMessage = transcript[transcript.length - 1];
    const currentSeq = lastMessage ? lastMessage.sequenceNumber : 0;

    // Check if we already processed up to this sequence number
    const existingInsights = await interviewInsightsRepository.findByInterviewId(interviewId);
    if (existingInsights && existingInsights.lastProcessedSequenceNumber >= currentSeq) {
      return existingInsights;
    }

    // Initialize provider dynamically to ensure it uses the factory
    const provider = getProvider();

    const systemPrompt = this.promptBuilder.buildSystemPrompt();
    const userPrompt = this.promptBuilder.buildUserPrompt(interview.topic, transcript);

    const messages = [
      {
        role: 'system',
        content: systemPrompt,
      },
      {
        role: 'user',
        content: userPrompt,
      },
    ];

    // Use low temperature to ensure strict adherence to JSON schema structure
    const response = await provider.generate(messages, { temperature: 0.1 });

    let cleanedContent = response.content.trim();

    // Strip markdown code block wrappers (e.g. ```json ... ```) if generated by the model
    if (cleanedContent.startsWith('```')) {
      cleanedContent = cleanedContent
        .replace(/^```(?:json)?\n?/i, '')
        .replace(/\n?```$/i, '')
        .trim();
    }

    let parsedInsights;
    try {
      parsedInsights = JSON.parse(cleanedContent);
    } catch (error) {
      console.error('Failed to parse AI insights JSON. Raw response:', response.content);
      throw new Error('Invalid JSON response from AI insights provider');
    }

    // Sanitize and supply defaults for safety
    const painPoints = Array.isArray(parsedInsights.painPoints)
      ? parsedInsights.painPoints.map(p => String(p).trim())
      : [];
    const featureRequests = Array.isArray(parsedInsights.featureRequests)
      ? parsedInsights.featureRequests.map(f => String(f).trim())
      : [];
    const sentiment = ['positive', 'neutral', 'negative'].includes(parsedInsights.sentiment)
      ? parsedInsights.sentiment
      : 'neutral';
    const summary = typeof parsedInsights.summary === 'string'
      ? parsedInsights.summary.trim()
      : '';

    const insightsData = {
      interviewId,
      painPoints,
      featureRequests,
      sentiment,
      summary,
      lastProcessedSequenceNumber: currentSeq,
    };

    return await interviewInsightsRepository.updateByInterviewId(interviewId, insightsData);
  }

  async getInsights(interviewId) {
    return await interviewInsightsRepository.findByInterviewId(interviewId);
  }
}

module.exports = new InsightsService();
